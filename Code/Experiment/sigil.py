def squash_to_32(blob):
    """Pads a cropped blob to a perfect square before resizing, preventing aspect-ratio distortion."""
    h, w = blob.shape[:2]
    side = max(w, h)

    # Create a black square canvas
    square = np.zeros((side, side), dtype=np.uint8)

    # Center the blob onto the canvas
    x_off = (side - w) // 2
    y_off = (side - h) // 2
    square[y_off:y_off+h, x_off:x_off+w] = blob

    # Squash the perfectly proportioned square to 32x32
    return cv2.resize(square, (32, 32))

def create_32x32_signature(img_path):
    """Generates a 32x32 hash using Histogram Skew to flawlessly detect polarity."""
    img = cv2.imread(img_path, cv2.IMREAD_GRAYSCALE)
    if img is None: return None

    blur = cv2.GaussianBlur(img, (5, 5), 0)

    # 1. Calculate the color extremes and the median background
    p5 = np.percentile(blur, 5)   # Darkest pixels
    p50 = np.median(blur)         # The Paper (Background)
    p95 = np.percentile(blur, 95) # Brightest pixels

    # 2. HISTOGRAM SKEW: Is the bright ink further from the paper than the dark ink?
    is_glowing = (p95 - p50) > (p50 - p5)

    if is_glowing:
        # Threshold for Light-on-Dark
        thresh_val = p50 + ((p95 - p50) * 0.40)
        _, thresh = cv2.threshold(blur, thresh_val, 255, cv2.THRESH_BINARY)
    else:
        # Threshold for Dark-on-Light
        thresh_val = p5 + ((p50 - p5) * 0.40)
        _, thresh = cv2.threshold(blur, thresh_val, 255, cv2.THRESH_BINARY_INV)

    # 3. Strong morph to connect fragmented pixels (like the bear trap and shield)
    clean = cv2.morphologyEx(thresh, cv2.MORPH_CLOSE, np.ones((5,5), np.uint8))

    # 4. Flawless bounding box (Requires templates to have clean edges!)
    coords = cv2.findNonZero(clean)
    if coords is not None:
        x, y, w, h = cv2.boundingRect(coords)
        blob = clean[y:y+h, x:x+w]
        return squash_to_32(blob) # Ensure your squash_to_32 helper is loaded!

    return None

