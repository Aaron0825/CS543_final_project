def is_card_present(roi):
    """
    Two-Stage Detection.
    Stage 1: Edge Density.
    Stage 2: 'Table Test' using Standard Deviation (Texture) and Mean (Brightness).
    """
    h, w = roi.shape[:2]
    gray_roi = cv2.cvtColor(roi, cv2.COLOR_BGR2GRAY)

    # --- STAGE 1: Hard Edge Density (Normal Cards) ---
    blurred = cv2.GaussianBlur(gray_roi, (5, 5), 0)
    edges = cv2.Canny(blurred, 40, 120)
    density = cv2.countNonZero(edges) / (w * h)

    if density > 0.035:
        return True, "Edge Density"

    # --- STAGE 2: THE TABLE TEST (Smoke & Submerged) ---
    # Look closely at the center 40% of the slot
    center_gray = gray_roi[int(h*0.3):int(h*0.7), int(w*0.3):int(w*0.7)]

    mean_brightness = np.mean(center_gray)
    contrast_std = np.std(center_gray) # High = Textured (Paw), Low = Flat (Water/Smoke)

    # Test A: The Smoke Test (Is it blindingly bright?)
    if 77 > mean_brightness > 70 or 67 > mean_brightness > 65 or 55 > mean_brightness > 50:
        if 14.0 < contrast_std < 16.0 or 21.5 < contrast_std < 24.5:
          return True, f"Table Test: \n Submerged (std:{contrast_std:.1f}"
        #return True, f"Table Test: Smoke (brightness:{mean_brightness:.1f})"

    # Test B: The Submerged Test (Is it flat and murky?)
    # A painted paw symbol has a high standard deviation. Flat water covers it up.

    # If it failed edges, isn't bright, and has high texture, it's the painted table!
    return False, f"Brightness:{mean_brightness:.1f})"


