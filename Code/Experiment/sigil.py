def create_32x32_signature(img_path):
    """Generates a 32x32 hash from a template image, fixing the hollow-shape bug."""
    img = cv2.imread(img_path, cv2.IMREAD_GRAYSCALE)
    if img is None: return None

    blur = cv2.GaussianBlur(img, (5, 5), 0)

    # Handle glowing sacrifice sigils vs normal ink
    is_sacrifice = "sacrifice" in img_path.lower()
    ink_val = np.percentile(blur, 80) if is_sacrifice else np.percentile(blur, 5)
    type_flag = cv2.THRESH_BINARY if is_sacrifice else cv2.THRESH_BINARY_INV
    thresh_offset = -30 if is_sacrifice else 30

    _, thresh = cv2.threshold(blur, ink_val + thresh_offset, 255, type_flag)

    # Lowered the kernel from 5x5 to 3x3 so we don't accidentally fill in hollow shields!
    clean = cv2.morphologyEx(thresh, cv2.MORPH_CLOSE, np.ones((3,3), np.uint8))

    # THE FIX: Find ALL ink pixels and draw a box around the absolute limits!
    coords = cv2.findNonZero(clean)
    if coords is not None:
        x, y, w, h = cv2.boundingRect(coords)
        blob = clean[y:y+h, x:x+w]
        return cv2.resize(blob, (32, 32))

    return None

