def check_for_stat(roi):
    gray = cv2.cvtColor(roi, cv2.COLOR_BGR2GRAY)

    # 1. Calculate the gradient (sharpness of edges)
    grad_x = cv2.Sobel(gray, cv2.CV_64F, 1, 0, ksize=3)
    grad_y = cv2.Sobel(gray, cv2.CV_64F, 0, 1, ksize=3)
    grad_mag = cv2.convertScaleAbs(cv2.magnitude(grad_x, grad_y))

    # 2. Threshold for only very sharp, high-contrast edges
    # This ignores faint background textures like lily pads and wings
    _, sharp_edges = cv2.threshold(grad_mag, 80, 255, cv2.THRESH_BINARY)

    # 3. Clean up tiny, isolated noise
    clean = cv2.morphologyEx(sharp_edges, cv2.MORPH_OPEN, np.ones((2, 2), np.uint8))

    # 4. Fuse nearby edges together
    # This groups the edges of the number and the icon into one massive blob
    fused = cv2.morphologyEx(clean, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))

    # 5. Check if any surviving blob is large enough to be a stat
    contours, _ = cv2.findContours(fused, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

    for cnt in contours:
        # A valid stat block (number + icon) will have a large fused area
        if cv2.contourArea(cnt) > 200:
            return True

    return False

