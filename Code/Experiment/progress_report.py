def detect_stat_via_contours(roi):
    """
    Finds chunks of ink (blobs). If the highest chunk is in the top
    portion of the bounding box, it's a number. If it's at the bottom,
    it's just a tribe symbol and should be ignored.
    """
    gray = cv2.cvtColor(roi, cv2.COLOR_BGR2GRAY)

    # 1. Adaptive threshold beats the shadows (like on the Bullfrog)
    thresh = cv2.adaptiveThreshold(gray, 255, cv2.ADAPTIVE_THRESH_GAUSSIAN_C, cv2.THRESH_BINARY_INV, 21, 15)

    # 2. Erase thin background lines (tree bark, water ripples)
    clean = cv2.morphologyEx(thresh, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))

    # 3. Find remaining blobs of ink
    contours, _ = cv2.findContours(clean, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

    valid_blobs = []
    for cnt in contours:
        x, y, w, h = cv2.boundingRect(cnt)
        # Numbers are thick. This ignores the clipped edges of center sigils.
        if cv2.contourArea(cnt) > 100 and w > 10 and h > 15:
            valid_blobs.append((x, y, w, h))

    if not valid_blobs:
        return False

    # 4. Sort to find the highest blob (minimum Y coordinate)
    valid_blobs.sort(key=lambda b: b[1])
    top_blob = valid_blobs[0]
    tx, ty, tw, th = top_blob

    # 5. Spatial Check
    # The number MUST be in the top ~60% of this specific ROI.
    # If the highest blob is lower than that, it's just a tribe icon.
    roi_height = roi.shape[0]
    blob_center_y = ty + (th / 2)

    if blob_center_y < (roi_height * 0.60):
        return True

    return False

