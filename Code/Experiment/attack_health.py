        # --- NATIVE SIGIL BAND ---
        # Search the middle section of the native, un-warped card
        band_y1, band_y2 = int(h * 0.45), int(h * 0.75)
        sigil_band = gray_roi[band_y1:band_y2, 0:w]
        sigil_band_edges = cv2.Canny(cv2.GaussianBlur(sigil_band, (3,3), 0), 50, 150)

        # --- STEP 1: FIND THE PERFECT TEMPLATE SCALE ---
        max_confidence = 0
        best_scale = 1.0

        # Sweep scales from 30% to 150% of your snip's original size
        for scale in np.linspace(0.3, 1.5, 15):
            r_w, r_h = int(tw * scale), int(th * scale)
            if r_w >= w or r_h >= (band_y2 - band_y1) or r_w == 0 or r_h == 0:
                continue

            # Resize the template, THEN extract its edges
            resized_template = cv2.resize(template, (r_w, r_h))
            resized_edges = cv2.Canny(cv2.GaussianBlur(resized_template, (3,3), 0), 50, 150)

            res = cv2.matchTemplate(sigil_band_edges, resized_edges, cv2.TM_CCOEFF_NORMED)
            _, max_val, _, _ = cv2.minMaxLoc(res)

            if max_val > max_confidence:
                max_confidence = max_val
                best_scale = scale

        # --- STEP 2: MATCH WITH THE BEST SCALE ---
        # If the best match breaks the confidence threshold, we have a sigil!
        if max_confidence > 0.12:
            final_w, final_h = int(tw * best_scale), int(th * best_scale)
            best_template = cv2.resize(template, (final_w, final_h))
            best_edges = cv2.Canny(cv2.GaussianBlur(best_template, (3,3), 0), 50, 150)

            res = cv2.matchTemplate(sigil_band_edges, best_edges, cv2.TM_CCOEFF_NORMED)
            locations = np.where(res >= 0.12)

            # --- STEP 3: NON-MAXIMUM SUPPRESSION ---
            matched_points = []
            for pt in zip(*locations[::-1]):
                is_duplicate = False
                for existing_pt in matched_points:
                    # Pythagorean distance check (15 pixel radius)
                    dist = np.sqrt((pt[0] - existing_pt[0])**2 + (pt[1] - existing_pt[1])**2)
                    if dist < 15:
                        is_duplicate = True
                        break

                if not is_duplicate:
                    matched_points.append(pt)

                    # Draw directly on the native image!
                    match_x = x + pt[0]
                    match_y = y + band_y1 + pt[1]

                    cv2.rectangle(output_img, (match_x, match_y), (match_x + final_w, match_y + final_h), (0, 255, 255), 4)
                    # Printing the confidence score helps with debugging thresholds
                    cv2.putText(output_img, f"AIR: {max_confidence:.2f}", (match_x, match_y - 10), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 255, 255), 2)

