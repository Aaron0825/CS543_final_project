def verify_stat_region(corner_roi, full_card_roi, is_attack=False):
    """
    Combines Global Reference Ink to ignore shadows/textures,
    with a Zonal Check to ignore bottom-corner tribe symbols.
    """
    # 1. Global Reference: Find true black ink from the whole card
    card_gray = cv2.cvtColor(full_card_roi, cv2.COLOR_BGR2GRAY)
    card_blurred = cv2.GaussianBlur(card_gray, (3, 3), 0)

    paper_val = np.percentile(card_blurred, 95)
    ink_val = np.percentile(card_blurred, 5)

    if paper_val - ink_val < 30:
        return False, 0.0

    stat_ink_threshold = ink_val + ((paper_val - ink_val) * 0.25)

    # 2. Apply strict global threshold to the corner
    corner_gray = cv2.cvtColor(corner_roi, cv2.COLOR_BGR2GRAY)
    corner_blurred = cv2.GaussianBlur(corner_gray, (3, 3), 0)

    _, mask = cv2.threshold(corner_blurred, stat_ink_threshold, 255, cv2.THRESH_BINARY_INV)
    mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))

    # Calculate overall mass
    total_pixels = corner_roi.shape[0] * corner_roi.shape[1]
    total_mass = cv2.countNonZero(mask) / total_pixels

    if total_mass < 0.02: # Completely empty
        return False, 0.0

    # 3. The Zonal Check (The Hybrid fix)
    if is_attack:
        # Check the top 55% of the ROI. The number must live here.
        # The tiny tribe symbols sit below this line.
        split_point = int(mask.shape[0] * 0.55)
        top_half = mask[:split_point, :]

        top_pixels = top_half.shape[0] * top_half.shape[1]
        top_mass = cv2.countNonZero(top_half) / top_pixels

        # If the top half is empty, it's just a tribe symbol, not an attack number
        if top_mass < 0.04:
            return False, total_mass

    # If it passes the zonal check (or is health) and has enough mass
    if total_mass > 0.03:
        return True, total_mass

    return False, total_mass

