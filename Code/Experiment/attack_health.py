# 3. Thresholds & THE NEW CALIBRATION MATRIX
DENSITY_THRESHOLD = 0.035

# Set custom rules for every single slot based on how the lighting hits it.
# (These are baseline numbers—you will need to tune these!)
CALIBRATION_MATRIX = {
    "Enemy_0": {"atk_min": 0.010, "paw_max": 0.030}, # Edge shadow
    "Enemy_1": {"atk_min": 0.012, "paw_max": 0.035}, # Bright center
    "Enemy_2": {"atk_min": 0.012, "paw_max": 0.035}, # Bright center
    "Enemy_3": {"atk_min": 0.010, "paw_max": 0.030}, # Edge shadow
    "Player_0": {"atk_min": 0.010, "paw_max": 0.030},
    "Player_1": {"atk_min": 0.012, "paw_max": 0.035},
    "Player_2": {"atk_min": 0.012, "paw_max": 0.035},
    "Player_3": {"atk_min": 0.010, "paw_max": 0.030},
}

# --- METHOD 1: THE FINDER ---
def verify_stat_region(corner_roi, full_card_roi, is_attack=False):
    card_gray = cv2.cvtColor(full_card_roi, cv2.COLOR_BGR2GRAY)
    card_blurred = cv2.GaussianBlur(card_gray, (3, 3), 0)

    paper_val = np.percentile(card_blurred, 95)
    ink_val = np.percentile(card_blurred, 5)

    if paper_val - ink_val < 30:
        return False, 0.0

    stat_ink_threshold = ink_val + ((paper_val - ink_val) * 0.25)

    corner_gray = cv2.cvtColor(corner_roi, cv2.COLOR_BGR2GRAY)
    corner_blurred = cv2.GaussianBlur(corner_gray, (3, 3), 0)

    _, mask = cv2.threshold(corner_blurred, stat_ink_threshold, 255, cv2.THRESH_BINARY_INV)
    mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))

    total_pixels = corner_roi.shape[0] * corner_roi.shape[1]
    total_mass = cv2.countNonZero(mask) / total_pixels

    # We removed the hardcoded 'if total_mass > 0.010' here.
    # The function now simply returns the raw math, and the loop makes the decision!
    return True, total_mass

# --- MAIN LOOP ---
extracted_stats = {}

for slot_name, coords in slots.items():
    x, y, w, h = coords

    # Fetch the specific rules for this slot!
    slot_rules = CALIBRATION_MATRIX[slot_name]
    atk_min = slot_rules["atk_min"]
    paw_max = slot_rules["paw_max"]

    roi = original_img[y:y+h, x:x+w]
    gray_roi = cv2.cvtColor(roi, cv2.COLOR_BGR2GRAY)
    blurred_roi = cv2.GaussianBlur(gray_roi, (5, 5), 0)
    edges_roi = cv2.Canny(blurred_roi, 40, 120)

    edge_density = cv2.countNonZero(edges_roi) / (w * h)

    if edge_density > DENSITY_THRESHOLD:
        cv2.rectangle(output_img, (x, y), (x + w, y + h), (0, 255, 0), 8)

        # The bounding boxes
        atk_y_start, atk_y_end = int(h * 0.70), int(h * 0.95)
        hp_y_start, hp_y_end = int(h * 0.70), int(h * 0.95)
        paw_y_start, paw_y_end = int(h * 0.85), int(h * 0.98)

        atk_x_start, atk_x_end = 0, int(w * 0.32)
        hp_x_start, hp_x_end = int(w * 0.68), w

        atk_roi = roi[atk_y_start:atk_y_end, atk_x_start:atk_x_end]
        paw_roi = roi[paw_y_start:paw_y_end, atk_x_start:atk_x_end]
        hp_roi = roi[hp_y_start:hp_y_end, hp_x_start:hp_x_end]

        # --- DYNAMIC ATTACK & PAW CASCADE ---
        _, atk_mass = verify_stat_region(atk_roi, roi, is_attack=True)
        _, paw_mass = verify_stat_region(paw_roi, roi, is_attack=True)

        # THE NEW RULE: Apply the custom slot rules
        if atk_mass > atk_min:
            if paw_mass < paw_max:
                extracted_stats[f"{slot_name}_Attack"] = "Found"
                cv2.rectangle(output_img, (x + atk_x_start, y + atk_y_start), (x + atk_x_end, y + atk_y_end), (0, 0, 255), 5)
                cv2.putText(output_img, f"A:{atk_mass:.3f}", (x + 5, y + h - 10), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 0, 255), 2)
            else:
                # DEBUGGER: Draw Yellow Box if Vetoed!
                cv2.rectangle(output_img, (x + atk_x_start, y + atk_y_start), (x + atk_x_end, y + atk_y_end), (0, 255, 255), 2)
                cv2.putText(output_img, f"VETO(P:{paw_mass:.3f})", (x + 5, y + h - 10), cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 255, 255), 2)

        # --- HEALTH CASCADE ---
        # Health icons are massive, keeping a safe universal threshold of 0.02
        _, hp_mass = verify_stat_region(hp_roi, roi, is_attack=False)
        if hp_mass > 0.020:
            extracted_stats[f"{slot_name}_Health"] = "Found"
            cv2.rectangle(output_img, (x + hp_x_start, y + hp_y_start), (x + hp_x_end, y + hp_y_end), (255, 0, 0), 5)
            cv2.putText(output_img, f"H:{hp_mass:.3f}", (x + int(w * 0.7) + 5, y + h - 10), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 0, 0), 2)

    else:
        cv2.rectangle(output_img, (x, y), (x + w, y + h), (0, 0, 255), 3)

