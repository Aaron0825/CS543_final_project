        # Always draw the Paw Box in Magenta to see what it's catching
        cv2.rectangle(output_img, (x + atk_x_start, y + paw_y_start), (x + atk_x_end, y + paw_y_end), (255, 0, 255), 3)
        cv2.putText(output_img, f"Paw:{paw_mass:.2f}", (x + 5, y + paw_y_end + 20), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 0, 255), 2)

        # --- HEALTH CASCADE ---
        has_hp, hp_mass = verify_stat_region(hp_roi, roi, is_attack=False)
        if has_hp:
            extracted_stats[f"{slot_name}_Health"] = "Found"
            cv2.rectangle(output_img, (x + hp_x_start, y + hp_y_start), (x + hp_x_end, y + hp_y_end), (255, 0, 0), 5)
            cv2.putText(output_img, f"Mass:{hp_mass:.2f}", (x + int(w * 0.7) + 5, y + h - 10), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 0, 0), 2)

        # --- NEW SOLID SHAPE SIGIL DETECTION ---
        if template is not None:
            band_y1, band_y2 = int(h * 0.40), int(h * 0.80)
            sigil_band = gray_roi[band_y1:band_y2, 0:w]

            band_thresh = cv2.adaptiveThreshold(sigil_band, 255, cv2.ADAPTIVE_THRESH_GAUSSIAN_C, cv2.THRESH_BINARY_INV, 21, 15)

            max_confidence = 0
            best_scale = 1.0

            for scale in np.linspace(0.3, 1.5, 15):
                r_w, r_h = int(tw * scale), int(th * scale)
                if r_w >= w or r_h >= (band_y2 - band_y1) or r_w == 0 or r_h == 0:
                    continue

                resized_template = cv2.resize(template, (r_w, r_h))
                _, template_thresh = cv2.threshold(resized_template, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)

                res = cv2.matchTemplate(band_thresh, template_thresh, cv2.TM_CCOEFF_NORMED)
                _, max_val, _, _ = cv2.minMaxLoc(res)

                if max_val > max_confidence:
                    max_confidence = max_val
                    best_scale = scale

            if max_confidence > 0.40:
                final_w, final_h = int(tw * best_scale), int(th * best_scale)
                best_template = cv2.resize(template, (final_w, final_h))
                _, best_edges = cv2.threshold(best_template, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)

