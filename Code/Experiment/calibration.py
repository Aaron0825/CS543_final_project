import cv2
import numpy as np
import matplotlib.pyplot as plt
import glob

# 1. Load your calibration image
# Swap this path to test different cards in the Enemy_0 slot
image_paths = glob.glob("*.png")

# 2. ISOLATED GRID (Only testing Enemy_0)
enemy_y, enemy_w, enemy_h = 175, 410, 580

slots = {
    "Enemy_0": [470, enemy_y, enemy_w, enemy_h]
}

# --- THE RAW MASS CALCULATOR ---
def get_ink_mass(corner_roi, full_card_roi):
    """Calculates the raw percentage of dark ink in a region."""
    card_gray = cv2.cvtColor(full_card_roi, cv2.COLOR_BGR2GRAY)
    card_blurred = cv2.GaussianBlur(card_gray, (3, 3), 0)

    paper_val = np.percentile(card_blurred, 95)
    ink_val = np.percentile(card_blurred, 5)

    if paper_val - ink_val < 30:
        return 0.0

    stat_ink_threshold = ink_val + ((paper_val - ink_val) * 0.25)

    corner_gray = cv2.cvtColor(corner_roi, cv2.COLOR_BGR2GRAY)
    corner_blurred = cv2.GaussianBlur(corner_gray, (3, 3), 0)

    _, mask = cv2.threshold(corner_blurred, stat_ink_threshold, 255, cv2.THRESH_BINARY_INV)
    mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))

    total_pixels = corner_roi.shape[0] * corner_roi.shape[1]
    return cv2.countNonZero(mask) / total_pixels

for image_path in image_paths:
    print(f"\n--- Processing: {image_path} ---")

    original_img = cv2.imread(image_path)
    if original_img is None:
        print(f"Failed to load {image_path}")
        continue

    output_img = original_img.copy()
    extracted_stats = {}

    # --- CALIBRATION LOOP ---
    for slot_name, coords in slots.items():
        x, y, w, h = coords

        roi = original_img[y:y+h, x:x+w]

        # Draw the main card bounding box
        cv2.rectangle(output_img, (x, y), (x + w, y + h), (0, 255, 0), 4)

        # The bounding boxes (Using your exact coordinates)
        atk_y_start, atk_y_end = int(h * 0.65), int(h * 0.85)
        paw_y_start, paw_y_end = int(h * 0.85), int(h * 0.95)
        atk_x_start, atk_x_end = 0, int(w * 0.28)

        atk_roi = roi[atk_y_start:atk_y_end, atk_x_start:atk_x_end]
        paw_roi = roi[paw_y_start:paw_y_end, atk_x_start:atk_x_end]

        # Calculate raw mass
        atk_mass = get_ink_mass(atk_roi, roi)
